import { describe, expect, it } from "vitest";
import { byId, check, projectFiles, TestRepo, type CheckSpec } from "../helpers/project.ts";

const SCHEMA = `
CREATE TABLE customers (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email text NOT NULL UNIQUE, name text NOT NULL);
CREATE TABLE orders (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id bigint NOT NULL REFERENCES customers(id), total numeric(20,2) NOT NULL, status text NOT NULL DEFAULT 'pending');
`;
const SEED = `
INSERT INTO customers (id, email, name) VALUES (1, 'a@example.test', 'Ann'), (2, 'b@example.test', 'Bob'), (3, 'c@example.test', 'Cy');
INSERT INTO orders (id, customer_id, total, status) VALUES (1, 1, 10.00, 'paid'), (2, 1, 10.00, 'paid'), (3, 2, 12345678901234567.89, 'paid'), (4, 3, 5.50, 'pending');
SELECT setval(pg_get_serial_sequence('customers', 'id'), 3);
SELECT setval(pg_get_serial_sequence('orders', 'id'), 4);
`;

function repo(checks: CheckSpec[], extra: Parameters<typeof projectFiles>[0] extends infer T ? Partial<T> : never = {}) {
  return TestRepo.create(projectFiles({ schema: SCHEMA, seed: SEED, checks, ...extra }));
}

describe("read query compatibility", () => {
  const reads: CheckSpec[] = [
    { id: "profile", category: "read", source: "sql/profile.sql", params: [1] },
    { id: "totals", category: "read", sql: "SELECT customer_id, total FROM orders" },
  ];
  const sql = { "profile.sql": "SELECT id, email, name FROM customers WHERE id = $1" };

  it("passes when nothing changes", async () => {
    const r = repo(reads, { sql });
    const res = await check(r);
    expect(res.report.exitCode).toBe(0);
    expect(res.report.summary.pass).toBe(2);
  });

  it("reports a renamed column as a regression with the PostgreSQL error and source location", async () => {
    const r = repo(reads, { sql });
    r.write({ "db/migrations/001_rename.sql": "ALTER TABLE customers RENAME COLUMN name TO full_name;" });
    const res = await check(r);
    const f = byId(res).get("profile")!;
    expect(res.report.exitCode).toBe(1);
    expect(f.classification).toBe("regression");
    expect(f.candidate.error?.code).toBe("42703");
    expect(f.candidate.error?.at).toEqual({ path: "sql/profile.sql", line: 1, column: 19 });
    expect(f.baseline.status).toBe("ok");
    expect(byId(res).get("totals")!.classification).toBe("pass");
  });

  it("reports a dropped table", async () => {
    const r = repo([{ id: "q", category: "read", sql: "SELECT id FROM orders" }]);
    r.write({ "db/migrations/001.sql": "DROP TABLE orders;" });
    const f = byId(await check(r)).get("q")!;
    expect(f.classification).toBe("regression");
    expect(f.candidate.error?.code).toBe("42P01");
  });

  it("detects changed output column types", async () => {
    const r = repo(reads, { sql });
    r.write({ "db/migrations/001.sql": "ALTER TABLE orders ALTER COLUMN total TYPE numeric(22,4);" });
    const f = byId(await check(r)).get("totals")!;
    expect(f.classification).toBe("changed-result");
    expect(f.reason).toBe("columns-changed");
    expect(f.columnDiff?.changes[0]).toContain("numeric(20,2) → numeric(22,4)");
  });

  it("compares output columns even when the result has zero rows", async () => {
    const r = repo([{ id: "empty", category: "read", sql: "SELECT id, total FROM orders WHERE false" }]);
    r.write({ "db/migrations/001.sql": "ALTER TABLE orders ALTER COLUMN id TYPE integer;" });
    const f = byId(await check(r)).get("empty")!;
    expect(f.baseline.rowCount).toBe(0);
    expect(f.classification).toBe("changed-result");
    expect(f.columnDiff?.changes[0]).toContain("bigint → integer");
  });

  it("detects changed result contents", async () => {
    const r = repo(reads, { sql });
    r.write({ "db/migrations/001.sql": "UPDATE orders SET total = total * 2 WHERE id = 4;" });
    const f = byId(await check(r)).get("totals")!;
    expect(f.classification).toBe("changed-result");
    expect(f.rowDiff).toMatchObject({ missingCount: 1, extraCount: 1 });
  });

  it("compares unordered results as multisets, preserving duplicate counts", async () => {
    const r = repo([{ id: "dups", category: "read", sql: "SELECT total FROM orders WHERE customer_id = 1" }]);
    // Same distinct values, one fewer duplicate.
    r.write({ "db/migrations/001.sql": "UPDATE orders SET customer_id = 3 WHERE id = 2;" });
    const f = byId(await check(r)).get("dups")!;
    expect(f.classification).toBe("changed-result");
    expect(f.rowDiff).toMatchObject({ missingCount: 1, extraCount: 0, baselineRowCount: 2, candidateRowCount: 1 });
  });

  it("ignores row order for unordered checks but not for ordered ones", async () => {
    const q = "SELECT id FROM orders ORDER BY CASE WHEN EXISTS (SELECT 1 FROM pg_class WHERE relname = 'reverse_flag') THEN -id ELSE id END";
    const r = repo([
      { id: "unordered", category: "read", sql: q },
      { id: "ordered", category: "read", sql: q, ordered: true },
    ]);
    r.write({ "db/migrations/001.sql": "CREATE TABLE reverse_flag ();" });
    const res = byId(await check(r));
    expect(res.get("unordered")!.classification).toBe("pass");
    expect(res.get("ordered")!.classification).toBe("changed-result");
    expect(res.get("ordered")!.rowDiff?.firstDifferenceAt).toBe(0);
  });

  it("preserves numeric precision beyond JavaScript numbers", async () => {
    const r = repo([{ id: "big", category: "read", sql: "SELECT total FROM orders WHERE id = 3" }], { rowSamples: 2 });
    // 12345678901234567.89 and .88 are the same IEEE double; text comparison still sees the change.
    expect(Number("12345678901234567.89")).toBe(Number("12345678901234567.88"));
    r.write({ "db/migrations/001.sql": "UPDATE orders SET total = 12345678901234567.88 WHERE id = 3;" });
    const f = byId(await check(r)).get("big")!;
    expect(f.classification).toBe("changed-result");
    expect(f.rowDiff?.samples).toEqual({ missing: [["12345678901234567.89"]], extra: [["12345678901234567.88"]] });
  });

  it("binds parameters, including numeric strings and NULL", async () => {
    const r = repo([
      { id: "p1", category: "read", sql: "SELECT id FROM orders WHERE total = $1", params: ["12345678901234567.89"] },
      { id: "p2", category: "read", sql: "SELECT count(*) FROM customers WHERE $1::text IS NULL OR name = $1", params: [null] },
      { id: "p3", category: "read", sql: "SELECT $1::int + $2::int AS s, $3::boolean AS b", params: [2, 3, true] },
    ]);
    r.write({ "x.txt": "query-only" });
    const res = await check(r);
    expect(res.report.exitCode).toBe(0);
    expect(byId(res).get("p1")!.baseline.rowCount).toBe(1);
  });

  it("marks a parameter count mismatch as an invalid fixture", async () => {
    const r = repo([{ id: "bad", category: "read", sql: "SELECT id FROM orders WHERE id = $1 AND total > $2", params: [1] }]);
    const res = await check(r);
    expect(byId(res).get("bad")!.classification).toBe("invalid-fixture");
    expect(res.report.exitCode).toBe(2);
  });

  it("is inconclusive — never a pass — when results exceed maxRows, even if the prefixes match", async () => {
    const r = repo([{ id: "big", category: "read", sql: "SELECT id FROM orders ORDER BY id", ordered: true }], { limits: { maxRows: 2 } });
    const res = await check(r);
    const f = byId(res).get("big")!;
    expect(f.classification).toBe("inconclusive");
    expect(f.reason).toBe("limit-exceeded");
    expect(res.report.exitCode).toBe(2);
  });

  it("is inconclusive when a statement exceeds the deadline", async () => {
    const r = repo([{ id: "slow", category: "read", sql: "SELECT pg_sleep(2)::text" }], { limits: { statementTimeoutMs: 200 } });
    const res = await check(r);
    expect(byId(res).get("slow")!).toMatchObject({ classification: "inconclusive", reason: "timeout" });
    expect(res.report.exitCode).toBe(2);
  });

  it("reports checks not started before the total run deadline as inconclusive", async () => {
    const r = repo([{ id: "a", category: "read", sql: "SELECT 1" }], { limits: { totalTimeoutMs: 1 } });
    const res = await check(r);
    expect(byId(res).get("a")!).toMatchObject({ classification: "inconclusive", reason: "deadline" });
    expect(res.report.exitCode).toBe(2);
  });

  it("reports a check that already fails at the baseline as an existing failure, not a regression", async () => {
    const r = repo([{ id: "broken", category: "read", sql: "SELECT nonexistent FROM customers" }]);
    const res = await check(r);
    expect(byId(res).get("broken")!.classification).toBe("baseline-failure");
    expect(res.report.exitCode).toBe(2);
  });

  it("rejects non-SELECT statements in read checks", async () => {
    const r = repo([{ id: "sneaky", category: "read", sql: "DELETE FROM orders" }]);
    expect(byId(await check(r)).get("sneaky")!.classification).toBe("invalid-fixture");
  });
});

describe("write compatibility", () => {
  const writes: CheckSpec[] = [
    { id: "signup", category: "write", source: "sql/signup.sql", params: ["new@example.test", "Nia"], expectRows: 1, ignoreColumns: ["id"] },
    { id: "pay", category: "write", sql: "UPDATE orders SET status = 'paid' WHERE status = 'pending'", expectRows: 1 },
    { id: "cleanup", category: "write", sql: "DELETE FROM orders WHERE status = 'paid'" },
    { id: "count-after", category: "read", sql: "SELECT count(*) FROM orders" },
  ];
  const sql = { "signup.sql": "INSERT INTO customers (email, name) VALUES ($1, $2) RETURNING id, email, name" };

  it("passes and isolates every write (later checks see the original data)", async () => {
    const r = repo(writes, { sql });
    const res = await check(r);
    expect(res.report.exitCode).toBe(0);
    const m = byId(res);
    expect(m.get("cleanup")!.baseline.affectedRows).toBe(3);
    // The DELETE above was rolled back: the read that runs after it sees all 4 orders.
    expect(m.get("count-after")!.classification).toBe("pass");
  });

  it("detects a new required column breaking an existing insert", async () => {
    const r = repo(writes, { sql });
    r.write({ "db/migrations/001.sql": "ALTER TABLE customers ADD COLUMN phone text; UPDATE customers SET phone = ''; ALTER TABLE customers ALTER COLUMN phone SET NOT NULL;" });
    const f = byId(await check(r)).get("signup")!;
    expect(f.classification).toBe("regression");
    expect(f.candidate.error?.code).toBe("23502");
  });

  it("detects a constraint change breaking a write", async () => {
    const r = repo(writes, { sql });
    r.write({ "db/migrations/001.sql": "ALTER TABLE orders ADD CONSTRAINT no_paid CHECK (status <> 'paid') NOT VALID;" });
    const f = byId(await check(r)).get("pay")!;
    expect(f.classification).toBe("regression");
    expect(f.candidate.error?.code).toBe("23514");
  });

  it("detects a renamed column breaking an application write", async () => {
    const r = repo(writes, { sql });
    r.write({ "db/migrations/001.sql": "ALTER TABLE customers RENAME COLUMN name TO full_name;" });
    const f = byId(await check(r)).get("signup")!;
    expect(f.classification).toBe("regression");
    expect(f.candidate.error?.code).toBe("42703");
  });

  it("detects unexpected affected-row counts", async () => {
    const r = repo(writes, { sql });
    r.write({ "db/migrations/001.sql": "UPDATE orders SET status = 'paid';" });
    const m = byId(await check(r));
    expect(m.get("pay")!).toMatchObject({ classification: "changed-result", reason: "row-count-changed" });
    // Without expectRows, the baseline count is the contract.
    expect(m.get("cleanup")!).toMatchObject({ classification: "changed-result", reason: "row-count-changed" });
  });

  it("checks deferred constraints even though the transaction is rolled back", async () => {
    const r = TestRepo.create(
      projectFiles({
        schema: "CREATE TABLE p (id int PRIMARY KEY); CREATE TABLE c (id int, p_id int);",
        seed: "INSERT INTO p VALUES (1);",
        checks: [{ id: "child", category: "write", sql: "INSERT INTO c VALUES (1, 99)", expectRows: 1 }],
      }),
    );
    r.write({ "db/migrations/001.sql": "ALTER TABLE c ADD CONSTRAINT fk FOREIGN KEY (p_id) REFERENCES p(id) DEFERRABLE INITIALLY DEFERRED NOT VALID;" });
    const f = byId(await check(r)).get("child")!;
    expect(f.classification).toBe("regression");
    expect(f.candidate.error?.code).toBe("23503");
  });

  it("does not treat generated ids as results when ignored, and compares RETURNING otherwise", async () => {
    const r = repo([
      { id: "ignored", category: "write", sql: "INSERT INTO orders (customer_id, total) VALUES (1, 1) RETURNING id, total", ignoreColumns: ["id"] },
      { id: "compared", category: "write", sql: "INSERT INTO orders (customer_id, total) VALUES (1, 1) RETURNING id, total" },
    ]);
    // The migration consumes sequence values, so generated ids differ between sides.
    r.write({ "db/migrations/001.sql": "SELECT nextval(pg_get_serial_sequence('orders', 'id')) FROM generate_series(1, 5);" });
    const m = byId(await check(r));
    expect(m.get("ignored")!.classification).toBe("pass");
    expect(m.get("compared")!).toMatchObject({ classification: "changed-result", reason: "rows-changed" });
  });

  it("reports an unexpected baseline row count as an existing baseline failure", async () => {
    const r = repo([{ id: "w", category: "write", sql: "UPDATE orders SET status = 'x' WHERE id = 999", expectRows: 1 }]);
    const res = await check(r);
    expect(byId(res).get("w")!.classification).toBe("baseline-failure");
    expect(res.report.exitCode).toBe(2);
  });
});

describe("data-integrity assertions", () => {
  const assertions: CheckSpec[] = [
    { id: "no-negative", category: "assertion", sql: "SELECT NOT EXISTS (SELECT 1 FROM orders WHERE total < 0)" },
    { id: "no-orphans", category: "assertion", sql: "SELECT NOT EXISTS (SELECT 1 FROM orders o LEFT JOIN customers c ON c.id = o.customer_id WHERE c.id IS NULL)" },
    { id: "count", category: "assertion", sql: "SELECT count(*) = 3 FROM customers" },
    { id: "revenue", category: "assertion", sql: "SELECT sum(total) = 12345678901234587.89 FROM orders WHERE status = 'paid'" },
  ];

  it("pass when the invariants hold", async () => {
    const res = await check(repo(assertions));
    expect(res.report.exitCode).toBe(0);
  });

  it("fail when a transformation breaks an invariant (SQL still runs)", async () => {
    const r = repo(assertions);
    r.write({ "db/migrations/001.sql": "UPDATE orders SET total = -total WHERE id = 4; UPDATE orders SET total = total + 0.01 WHERE id = 3;" });
    const res = await check(r);
    const m = byId(res);
    expect(res.migrations?.added).toHaveLength(1);
    expect(res.report.migrations.new[0]!.status).toBe("applied");
    expect(m.get("no-negative")!.classification).toBe("failed-assertion");
    expect(m.get("revenue")!.classification).toBe("failed-assertion");
    expect(m.get("count")!.classification).toBe("pass");
    expect(res.report.exitCode).toBe(1);
  });

  it("distinguish an assertion that was already false before the change", async () => {
    const r = repo([{ id: "wrong-count", category: "assertion", sql: "SELECT count(*) = 99 FROM customers" }]);
    const res = await check(r);
    expect(byId(res).get("wrong-count")!).toMatchObject({ classification: "baseline-failure", reason: "assertion-false-at-baseline" });
    expect(res.report.exitCode).toBe(2);
  });

  it.each([
    ["non-boolean", "SELECT count(*) FROM customers"],
    ["multiple rows", "SELECT true FROM customers"],
    ["multiple columns", "SELECT true, true"],
    ["NULL", "SELECT NULL::boolean"],
  ])("reject an invalid assertion fixture (%s)", async (_n, sqlText) => {
    const res = await check(repo([{ id: "bad", category: "assertion", sql: sqlText }]));
    expect(byId(res).get("bad")!.classification).toBe("invalid-fixture");
    expect(res.report.exitCode).toBe(2);
  });
});

describe("migrations and baseline setup", () => {
  it("reports a failed migration separately from application checks", async () => {
    const r = repo([{ id: "a", category: "read", sql: "SELECT 1" }]);
    r.write({ "db/migrations/001_ok.sql": "ALTER TABLE customers ADD COLUMN x int;", "db/migrations/002_bad.sql": "SELECT 1;\nALTER TABLE nope ADD COLUMN y int;", "db/migrations/003_after.sql": "SELECT 1;" });
    const res = await check(r);
    expect(res.report.exitCode).toBe(1);
    expect(res.report.migrations.new.map((m) => m.status)).toEqual(["applied", "failed", "not-run"]);
    expect(res.report.migrations.new[1]!.error).toMatchObject({ code: "42P01", at: { path: "db/migrations/002_bad.sql", line: 2 } });
    expect(byId(res).get("a")!.classification).toBe("skipped");
  });

  it("applies baseline migrations to both sides and only new ones to the candidate, in filename order", async () => {
    const r = repo([{ id: "cols", category: "read", sql: "SELECT column_name FROM information_schema.columns WHERE table_name = 'customers'" }], {
      migrations: { "001_a.sql": "ALTER TABLE customers ADD COLUMN a int;" },
    });
    r.write({ "db/migrations/003_c.sql": "ALTER TABLE customers RENAME COLUMN b TO c;", "db/migrations/002_b.sql": "ALTER TABLE customers ADD COLUMN b int;" });
    const res = await check(r);
    expect(res.report.migrations.baseline).toEqual(["db/migrations/001_a.sql"]);
    expect(res.report.migrations.new.map((m) => [m.file, m.status])).toEqual([
      ["db/migrations/002_b.sql", "applied"],
      ["db/migrations/003_c.sql", "applied"],
    ]);
    expect(byId(res).get("cols")!).toMatchObject({ classification: "changed-result", rowDiff: { extraCount: 1, missingCount: 0 } });
  });

  it("flags an edited, already-applied migration instead of guessing", async () => {
    const r = repo([{ id: "a", category: "read", sql: "SELECT 1" }], { migrations: { "001.sql": "ALTER TABLE customers ADD COLUMN a int;" } });
    r.write({ "db/migrations/001.sql": "ALTER TABLE customers ADD COLUMN a bigint;" });
    const res = await check(r);
    expect(res.report.history).toEqual([expect.objectContaining({ kind: "edited-migration", blocking: true })]);
    expect(res.report.exitCode).toBe(2);
  });

  it("flags removed and out-of-order migrations", async () => {
    const r = repo([{ id: "a", category: "read", sql: "SELECT 1" }], { migrations: { "002.sql": "SELECT 1;" } });
    r.write({ "db/migrations/002.sql": null, "db/migrations/001.sql": "SELECT 1;" });
    const res = await check(r);
    expect(res.report.history.map((h) => h.kind).sort()).toEqual(["out-of-order-migration", "removed-migration"]);
    expect(res.report.exitCode).toBe(2);
  });

  it("uses baseline sample data even if the change edits the seed", async () => {
    const r = repo([{ id: "count", category: "assertion", sql: "SELECT count(*) = 3 FROM customers" }]);
    r.write({ "db/migrations/001.sql": "DELETE FROM orders WHERE customer_id = 3; DELETE FROM customers WHERE id = 3;", "db/seed.sql": SEED + "\nINSERT INTO customers (id, email, name) VALUES (4, 'd@example.test', 'Di');" });
    const res = await check(r);
    expect(byId(res).get("count")!.classification).toBe("failed-assertion");
    expect(res.report.history).toEqual([expect.objectContaining({ kind: "seed-changed", blocking: false })]);
  });

  it("flags edits to the bootstrap schema file", async () => {
    const r = repo([{ id: "a", category: "read", sql: "SELECT 1" }]);
    r.write({ "db/schema.sql": SCHEMA + "\nCREATE TABLE extra (id int);" });
    const res = await check(r);
    expect(res.report.history[0]!.kind).toBe("schema-edited");
    expect(res.report.exitCode).toBe(2);
  });

  it("exits 2 when the baseline schema itself fails", async () => {
    const r = TestRepo.create(projectFiles({ schema: "CREATE TABLE t (id int);\nCREATE TABLE t (id int);", checks: [] }));
    const res = await check(r);
    expect(res.report.problems[0]).toMatchObject({ kind: "baseline" });
    expect(res.report.problems[0]!.message).toContain("db/schema.sql:2");
    expect(res.report.exitCode).toBe(2);
  });

  it("exits 2 for invalid configuration", async () => {
    const r = repo([{ id: "a", category: "read", sql: "SELECT 1" }]);
    r.write({ "crashpad.config.json": JSON.stringify({ version: 1, schema: "../../etc/passwd", migrations: "m", checks: "checks.json" }) });
    const res = await check(r);
    expect(res.report.problems[0]!.kind).toBe("config");
    expect(res.report.exitCode).toBe(2);
    expect(res.report.status).toBe("error");
  });

  it("never includes database credentials in the report", async () => {
    const res = await check(repo([{ id: "a", category: "read", sql: "SELECT 1" }]));
    expect(JSON.stringify(res.report)).not.toMatch(/postgres(ql)?:\/\//);
  });
});
